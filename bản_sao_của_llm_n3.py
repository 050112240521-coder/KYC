CASE_RE = re.compile(r"^(?:hs|ho[\s_\-]*so|case|kh|nguoi|person)[\s_\-]*0*(\d+)|^0*(\d+)[\s_\-]")
UNASSIGNED = "Chưa gán hồ sơ"


def assign_cases(df: pd.DataFrame, mode: str = "prefix") -> dict:
    files = list(dict.fromkeys(df["Tên file"]))
    if mode == "single":
        return {f: "HS1" for f in files}
    out = {}
    for f in files:
        m = CASE_RE.search(norm(os.path.splitext(f)[0]))
        out[f] = f"HS{int(m.group(1) or m.group(2))}" if m else None
    if all(v is None for v in out.values()):
        return {f: "HS1" for f in files}
    return {f: (v or UNASSIGNED) for f, v in out.items()}


def collect_case_docs(df_case: pd.DataFrame):
    docs, invalid = {}, []
    for (fname, dtype), g in df_case.groupby(["Tên file", "Loại tài liệu"], sort=False):
        if dtype == DT_INVALID:
            invalid.append(fname)
            continue
        entry = docs.setdefault(dtype, {"fields": {}, "files": []})
        entry["files"].append(fname)
        for _, r in g.iterrows():
            name, val = str(r["Tên trường"]), str(r["Giá trị trích xuất"]).strip()
            if val and val != MISSING and name not in entry["fields"]:
                entry["fields"][name] = val
    return docs, invalid


