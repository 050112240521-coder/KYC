def internal_checks(dtype: str, doc: dict):
    f = doc["fields"]
    id_name = {DT_CCCD: "Số CCCD", DT_GXNDC: "Số CMND/CCCD"}.get(dtype)
    id_val = _digits(f.get(id_name, "")) if id_name else ""
    if len(id_val) != 12:
        return []
    dob_name = "Ngày sinh" if dtype == DT_CCCD else "Năm sinh"
    dob = parse_dob(f.get(dob_name, "")) if f.get(dob_name) else None
    gender = f.get("Giới tính", "")
    code = int(id_val[3])
    exp_year = (19 + code // 2) * 100 + int(id_val[4:6])
    exp_gender = "Nam" if code % 2 == 0 else "Nữ"
    tag, rows = DOC_SHORT[dtype], []

    if dob:
        ok = dob[2] == exp_year
        rows.append(("Số CCCD ↔ năm sinh", f"{tag}: {id_val}", f"{tag}: năm sinh {dob[2]}",
                     ST_OK if ok else ST_BAD, 100.0 if ok else 0.0,
                     "" if ok else f"Số CCCD cho biết sinh năm {exp_year}, nhưng tài liệu ghi {dob[2]}"))
    if gender:
        ok = norm(gender) == norm(exp_gender)
        rows.append(("Số CCCD ↔ giới tính", f"{tag}: {id_val}", f"{tag}: giới tính {gender}",
                     ST_OK if ok else ST_BAD, 100.0 if ok else 0.0,
                     "" if ok else f"Số CCCD cho biết giới tính {exp_gender}, nhưng tài liệu ghi {gender}"))
    ok = id_val[:3] in PROVINCE_CODES
    rows.append(("Số CCCD ↔ mã tỉnh", f"{tag}: {id_val}", f"Mã tỉnh {id_val[:3]}",
                 ST_OK if ok else ST_WARN, 100.0 if ok else 0.0,
                 "" if ok else "3 số đầu không phải mã tỉnh/thành hợp lệ — nghi số CCCD giả/sai"))
    return rows


