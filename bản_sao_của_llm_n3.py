DEBUG_OCR = {}     # lưu văn bản OCR thô của từng file để kiểm tra khi trích xuất sai


def process_file(path: str):
    """Xử lý 1 file: đọc -> phân loại -> trích xuất. Trả về (các dòng DataFrame, dòng tóm tắt)."""
    fname = os.path.basename(path)
    try:
        lines, is_image = read_document(path)
    except Exception as e:
        return [[fname, DT_INVALID, "-", f"Lỗi đọc file: {e}"]], [fname, DT_INVALID, "Lỗi đọc file"]

    DEBUG_OCR[fname] = "\n".join(f"{i:02d} | {l.text}" for i, l in enumerate(lines))
    doc_type, _, _ = classify_document(lines)
    if doc_type is None:
        return ([[fname, DT_INVALID, "-", "Không thuộc 3 loại tài liệu được hỗ trợ"]],
                [fname, DT_INVALID, "Đã gắn cờ không hợp lệ"])

    rows = [[fname, doc_type, name, val if val else "(không tìm thấy)"]
            for name, val in extract_fields(lines, doc_type, is_image)]
    n_ok = sum(1 for r in rows if r[3] != "(không tìm thấy)")
    return rows, [fname, doc_type, f"Trích xuất {n_ok}/{len(rows)} trường"]


def run_pipeline(paths, progress=None):
    """Chạy toàn bộ danh sách file -> (DataFrame chi tiết, DataFrame tóm tắt phân loại)."""
    all_rows, summary = [], []
    for i, p in enumerate(paths):
        if progress:
            progress((i, len(paths)), desc=f"Đang xử lý {os.path.basename(p)}")
        rows, sm = process_file(p)
        all_rows += rows
        summary.append(sm)
    df = pd.DataFrame(all_rows, columns=COLUMNS)
    df_sum = pd.DataFrame(summary, columns=["Tên file", "Loại tài liệu", "Kết quả"])
    return df, df_sum


def df_to_html(df: pd.DataFrame) -> str:
    """Bảng HTML đẹp, nhóm theo file / loại tài liệu."""
    css = """<style>
    .idp{border-collapse:collapse;width:100%;font-family:system-ui,Segoe UI,sans-serif;font-size:14px}
    .idp th{background:#1f4e79;color:#fff;padding:9px 10px;text-align:left}
    .idp td{padding:7px 10px;border-bottom:1px solid rgba(128,128,128,.28);vertical-align:middle}
    .idp tr.grp td{background:rgba(31,78,121,.18);font-weight:700;font-size:15px}
    .idp td.miss{opacity:.55;font-style:italic}
    </style>"""
    out = [css, "<table class='idp'><tr><th style='width:28%'>Tên trường</th><th>Giá trị trích xuất</th></tr>"]
    for (fname, dtype), g in df.groupby(["Tên file", "Loại tài liệu"], sort=False):
        icon = "⚠️" if dtype == DT_INVALID else "📄"
        out.append(f"<tr class='grp'><td colspan='2'>{icon} {html.escape(fname)} &nbsp;→&nbsp; {html.escape(dtype)}</td></tr>")
        for _, r in g.iterrows():
            val = str(r["Giá trị trích xuất"])
            cls = " class='miss'" if val == "(không tìm thấy)" else ""
            out.append(f"<tr><td>{html.escape(r['Tên trường'])}</td><td{cls}>{html.escape(val)}</td></tr>")
    out.append("</table>")
    return "".join(out)


def summary_to_html(df_sum: pd.DataFrame) -> str:
    rows = ["<table class='idp'><tr>" + "".join(f"<th>{html.escape(c)}</th>" for c in df_sum.columns) + "</tr>"]
    for _, r in df_sum.iterrows():
        bad = r["Loại tài liệu"] == DT_INVALID
        style = " style='color:#d64545;font-weight:700'" if bad else ""
        rows.append("<tr>" + "".join(
            f"<td{style if c == 'Loại tài liệu' else ''}>{html.escape(str(r[c]))}</td>" for c in df_sum.columns) + "</tr>")
    rows.append("</table>")
    return "".join(rows)

