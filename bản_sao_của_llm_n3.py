# ---------------------------- tiện ích ------------------------------
def _fold(s: str) -> str:
    """Chuẩn hóa nhẹ (giữ dấu): NFC + gộp khoảng trắng + chữ thường."""
    return re.sub(r"\s+", " ", unicodedata.normalize("NFC", s)).strip().casefold()


def _alnum_tokens(s: str):
    return re.sub(r"[^a-z0-9\s]", " ", norm(s)).split()


def _digits(s: str) -> str:
    return re.sub(r"\D", "", s or "")


def _lev(a: str, b: str) -> int:
    """Khoảng cách Levenshtein (số ký tự phải sửa để a -> b)."""
    if a == b:
        return 0
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]


# ----------------------- các hàm so sánh theo kiểu ------------------
def cmp_name(a, b):
    ta, tb = _alnum_tokens(a), _alnum_tokens(b)
    ja, jb = " ".join(ta), " ".join(tb)
    if _fold(a) == _fold(b):
        return ST_OK, 100.0, ""
    if ja == jb:
        return ST_WARN, 97.0, "Chỉ khác dấu tiếng Việt (nghi lỗi OCR hoặc gõ sai dấu)"
    if sorted(ta) == sorted(tb):
        return ST_WARN, 90.0, "Cùng các từ nhưng khác thứ tự (họ/tên đệm/tên bị đảo)"
    r = round(_fuzzy_ratio(ja, jb), 1)
    if r >= TH_NAME_WARN:
        return ST_WARN, r, "Tên gần giống nhau, lệch vài ký tự (nghi lỗi OCR/đánh máy)"
    return ST_BAD, r, "Họ tên khác nhau giữa 2 tài liệu"


def cmp_id(a, b):
    da, db = _digits(a), _digits(b)
    if not da or not db:
        return ST_NA, None, "Không đọc được dãy số"
    if da == db:
        return ST_OK, 100.0, ""
    if {len(da), len(db)} == {9, 12}:
        return ST_WARN, None, "Một bên là CMND 9 số, bên kia là CCCD 12 số — không so trực tiếp được, cần kiểm tra thủ công"
    d = _lev(da, db)
    score = round(100 * (1 - d / max(len(da), len(db))), 1)
    if len(da) == len(db) and d == 1:
        return ST_WARN, score, "Lệch 1 chữ số (nghi lỗi OCR hoặc nhập sai)"
    return ST_BAD, score, f"Số giấy tờ khác nhau ({d} ký tự lệch)"


def parse_dob(s: str):
    """-> (ngày, tháng, năm) hoặc (None, None, năm) nếu chỉ có năm; None nếu không đọc được."""
    m = DATE_RE.search(s or "")
    if m:
        d, mo, y = map(int, m.groups())
        return d, mo, y
    m = YEAR_RE.search(s or "")
    return (None, None, int(m.group(1))) if m else None


def cmp_dob(a, b):
    pa, pb = parse_dob(a), parse_dob(b)
    if not pa or not pb:
        return ST_WARN, None, "Không chuẩn hóa được ngày sinh để so sánh"
    if pa[0] and pb[0]:
        if pa == pb:
            return ST_OK, 100.0, ""
        if pa[2] == pb[2] and (pa[0], pa[1]) == (pb[1], pb[0]):
            return ST_WARN, 85.0, "Nghi nhầm vị trí ngày ↔ tháng"
        sa, sb = "%02d%02d%04d" % pa, "%02d%02d%04d" % pb
        d = _lev(sa, sb)
        if d <= 1:
            return ST_WARN, 90.0, "Lệch 1 chữ số (nghi lỗi OCR)"
        return ST_BAD, round(100 * (1 - d / 8), 1), "Ngày sinh khác nhau"
    if pa[2] == pb[2]:
        return ST_OK, 100.0, "Chỉ so sánh được NĂM sinh (một tài liệu chỉ ghi năm)"
    return ST_BAD, 0.0, "Năm sinh khác nhau"


def cmp_gender(a, b):
    return (ST_OK, 100.0, "") if norm(a) == norm(b) else (ST_BAD, 0.0, "Giới tính khác nhau")


# ---- Địa chỉ: tách theo dấu phẩy, bỏ từ hành chính (Phường/Xã/Quận/Huyện/Tỉnh...), viết tắt -> đầy đủ ----
ADDR_ABBR = {"tp": "thanh pho", "tt": "thi tran", "tx": "thi xa", "q": "quan", "h": "huyen",
             "p": "phuong", "x": "xa", "kp": "khu pho"}
ADMIN_WORDS_RE = re.compile(r"\b(thanh pho|thi tran|thi xa|khu pho|tinh|quan|huyen|phuong|xa|"
                            r"thon|xom|ap|duong|so)\b")
LEVEL_NAMES = ["Tỉnh/Thành phố", "Quận/Huyện", "Phường/Xã"]


def addr_segments(s: str):
    segs = []
    for part in re.split(r"[,;]", s or ""):
        n = norm(part)
        n = re.sub(r"\btphcm\b", "thanh pho ho chi minh", n)
        n = re.sub(r"\bhcmc?\b", "ho chi minh", n)
        n = re.sub(r"[^a-z0-9\s]", " ", n)
        toks = [ADDR_ABBR.get(t, t) for t in n.split()]
        toks = [re.sub(r"^0+(\d)", r"\1", t) for t in toks]           # 'phuong 05' == 'phuong 5'
        n = ADMIN_WORDS_RE.sub(" ", " ".join(toks))
        n = re.sub(r"\s+", " ", n).strip()
        if n:
            segs.append(n)
    return segs


def _seg_status(x: str, y: str):
    r = _fuzzy_ratio(x, y)
    same_nums = re.findall(r"\d+", x) == re.findall(r"\d+", y)
    if r >= TH_ADDR_OK and same_nums:
        return "ok", r
    if r >= TH_ADDR_WARN:
        return "warn", r
    return "bad", r


def _level_name(i_from_end: int) -> str:
    return LEVEL_NAMES[i_from_end] if i_from_end < len(LEVEL_NAMES) else "Chi tiết (số nhà/đường/thôn)"


def cmp_address(a, b):
    sa, sb = addr_segments(a), addr_segments(b)
    if not sa or not sb:
        return ST_NA, None, "Không đọc được địa chỉ"
    ja, jb = " ".join(sa), " ".join(sb)
    full = round(_fuzzy_ratio(ja, jb), 1)
    if ja.split() == jb.split():
        note = "" if sa == sb else "Cùng nội dung, khác cách ngắt dấu phẩy/viết tắt"
        return ST_OK, 100.0, note

    if min(len(sa), len(sb)) == 1 and max(len(sa), len(sb)) > 1:
        st, _ = _seg_status(ja, jb)
        return {"ok": (ST_OK, full, ""),
                "warn": (ST_WARN, full, "Địa chỉ gần giống nhưng khác chữ/chữ số — cần kiểm tra"),
                "bad": (ST_BAD, full, "Địa chỉ khác nhau")}[st]

    ra, rb = sa[::-1], sb[::-1]
    bad, warn = [], []
    for i in range(min(len(ra), len(rb))):
        st, _ = _seg_status(ra[i], rb[i])
        if st == "bad":
            bad.append(_level_name(i))
        elif st == "warn":
            warn.append(_level_name(i))
    if bad:
        return ST_BAD, full, "Khác nhau ở: " + ", ".join(bad)
    if warn:
        return ST_WARN, full, "Gần giống nhưng lệch ở: " + ", ".join(warn) + " (nghi lỗi OCR hoặc khác chữ số)"
    if len(sa) != len(sb):
        who = "tài liệu 1" if len(sa) < len(sb) else "tài liệu 2"
        return ST_WARN, full, f"Các cấp chung đều khớp nhưng {who} thiếu thành phần địa chỉ (vd số nhà/thôn/xã)"
    return ST_OK, full, ""


