def load_and_run(paths, group_mode="prefix", progress=None):
    csvs = [p for p in paths if p.lower().endswith(".csv")]
    docs = [p for p in paths if not p.lower().endswith(".csv")]
    frames = []
    if docs:
        df_ex, _ = run_pipeline(docs, progress)
        frames.append(df_ex)
    for p in csvs:
        frames.append(pd.read_csv(p, encoding="utf-8-sig", dtype=str).fillna(""))
    df_extract = pd.concat(frames, ignore_index=True)
    df_cross, df_sum = cross_check_all(df_extract, group_mode)
    return df_extract, df_cross, df_sum

