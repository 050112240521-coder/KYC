def _row(case, label, d1, v1, d2, v2, score, status, sev, note):
    return [case, label, d1, v1 or "—", d2, v2 or "—", score if score is not None else "", status, sev, note]


def compare_docs(case, ref_type, ref, oth_type, oth):
    rows = []
    oname = oth["fields"].get("Tên khách hàng", "") if oth_type == DT_KYC else ""
    org_kyc = oth_type == DT_KYC and is_org_name(oname)
    for sp in CROSS_FIELDS:
        fa, fb = sp.fields.get(ref_type), sp.fields.get(oth_type)
        if not fa or not fb:
            continue
        va, vb = ref["fields"].get(fa, ""), oth["fields"].get(fb, "")
        d1, d2 = DOC_SHORT[ref_type], DOC_SHORT[oth_type]
        args = (case, sp.label, d1, va, d2, vb)
        if org_kyc and sp.kind == "name":
            rows.append(_row(*args, None, ST_NA, sp.severity, "KYC của tổ chức: không so tên pháp nhân với tên cá nhân"))
        elif org_kyc and sp.kind == "id" and vb and len(_digits(vb)) not in (9, 12):
            rows.append(_row(*args, None, ST_NA, sp.severity, "Số ID của KYC là mã tổ chức (MST/ĐKKD), không phải CMND/CCCD"))
        elif not va or not vb:
            miss = [d for d, v in ((d1, va), (d2, vb)) if not v]
            rows.append(_row(*args, None, ST_NA, sp.severity, "Thiếu dữ liệu ở: " + ", ".join(miss)))
        else:
            status, score, note = CMP[sp.kind](va, vb)
            if sp.soft and status in (ST_BAD, ST_WARN):
                status = ST_INFO
                note = (note + ". " if note else "") + "Có thể hợp lệ nếu khách hàng đang ở nơi khác nơi thường trú"
            rows.append(_row(*args, score, status, sp.severity, note))
    return rows


def verdict_of(rows) -> str:
    st = [r[7] for r in rows]
    if not any(s in (ST_OK, ST_WARN, ST_BAD) for s in st):
        return "⚪ KHÔNG ĐỦ DỮ LIỆU ĐỂ ĐỐI CHIẾU"
    if any(r[7] == ST_BAD and r[8] == SEV_HIGH for r in rows):
        return "🔴 BẤT ĐỒNG NGHIÊM TRỌNG"
    if ST_BAD in st:
        return "🟠 CÓ BẤT ĐỒNG"
    if ST_WARN in st:
        return "🟡 CẦN KIỂM TRA THỦ CÔNG"
    if ST_NA in st:
        return "🟢 KHỚP (một số trường không đối chiếu được do thiếu dữ liệu)"
    return "🟢 CÁC TÀI LIỆU KHỚP NHAU"


def cross_check_case(case: str, df_case: pd.DataFrame):
    docs, invalid = collect_case_docs(df_case)
    rows = []
    present = [t for t in REF_PRIORITY if t in docs]

    if len(present) >= 2:
        ref_type = present[0]
        for oth_type in present[1:]:
            rows += compare_docs(case, ref_type, docs[ref_type], oth_type, docs[oth_type])
    for t in present:
        for label, v1, v2, st, sc, note in internal_checks(t, docs[t]):
            rows.append(_row(case, "Nội bộ: " + label, DOC_SHORT[t], v1.split(": ", 1)[-1],
                             DOC_SHORT[t], v2.split(": ", 1)[-1], sc, st, SEV_HIGH, note))

    desc = ", ".join(f"{DOC_SHORT[t]} ({len(docs[t]['files'])} file)" for t in present) or "—"
    if invalid:
        desc += f" | ⚠️ File không hợp lệ: {', '.join(invalid)}"
    if len(present) < 2:
        desc += " | ⚠️ Chưa đủ ≥2 loại tài liệu để đối chiếu chéo"
    cnt = {s: sum(1 for r in rows if r[7] == s) for s in (ST_OK, ST_WARN, ST_BAD, ST_INFO, ST_NA)}
    summ = [case, desc, len(rows), cnt[ST_OK], cnt[ST_WARN], cnt[ST_BAD], cnt[ST_INFO], cnt[ST_NA], verdict_of(rows)]
    return rows, summ


def cross_check_all(df: pd.DataFrame, group_mode: str = "prefix"):
    df = df.copy()
    for c in ("Tên file", "Loại tài liệu", "Tên trường", "Giá trị trích xuất"):
        if c not in df.columns:
            raise ValueError(f"Thiếu cột '{c}' trong bảng trích xuất")
    df["Giá trị trích xuất"] = df["Giá trị trích xuất"].fillna("").astype(str)
    mapping = assign_cases(df, group_mode)
    df["__case"] = df["Tên file"].map(mapping)
    all_rows, summaries = [], []
    for case in sorted(df["__case"].unique(), key=lambda c: (c == UNASSIGNED, int(re.sub(r"\D", "", c) or 0), c)):
        rows, summ = cross_check_case(case, df[df["__case"] == case])
        all_rows += rows
        summaries.append(summ)
    return pd.DataFrame(all_rows, columns=CROSS_COLS), pd.DataFrame(summaries, columns=SUM_COLS)


